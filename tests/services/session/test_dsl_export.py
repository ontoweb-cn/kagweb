def test_mermaid_label_sanitization_and_clip() -> None:
    doc = {
        "version": 1,
        "trace": [
            {
                "node": "turn:1",
                "kind": "user",
                "text_preview": 'quote " hash # newline\nend ' + "x" * 60,
            },
            {"node": "turn:2", "kind": "assistant", "capability": "deep_solve"},
        ],
    }
    lines = dsl_to_mermaid(doc).splitlines()
    # `"`/`#`/newline scrubbed to spaces; clipped at 48 chars + ellipsis
    expected_label = "User: quote   hash   newline end " + "x" * 21 + "..."
    assert lines[1] == f'    turn_1["{expected_label}"]'
    assert lines[2] == '    turn_2["Assistant (deep_solve)"]'


def test_mermaid_id_dedupe_on_collision() -> None:
    doc = {
        "version": 1,
        "trace": [
            {"node": "a:b", "kind": "user", "text_preview": "one"},
            {"node": "a/b", "kind": "assistant"},  # sanitizes to the same a_b
        ],
    }
    lines = dsl_to_mermaid(doc).splitlines()
    assert lines[1] == '    a_b["User: one"]'
    assert lines[2] == '    a_b_1["Assistant"]'
    assert lines[3] == "    a_b --> a_b_1"


