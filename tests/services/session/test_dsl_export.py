def test_cli_mermaid_print_survives_rich_markup_in_user_text(monkeypatch) -> None:
    # #75: user text like "[/b]" is a rich closing tag — printing the
    # mermaid export used to raise MarkupError and crash the CLI.
    from deepmentor_cli import session_cmd

    class _StubApp:
        async def get_session(self, session_id: str) -> dict:
            return {
                "messages": [
                    _msg(1, "user", None, content="how do I write [/b] in markdown?"),
                ]
            }

    monkeypatch.setattr(session_cmd, "DeepMentorApp", _StubApp)
    from typer.testing import CliRunner

    from deepmentor_cli.main import app

    result = CliRunner().invoke(app, ["session", "trace", "s1", "--format", "mermaid"])
    assert result.exit_code == 0
    assert "[/b]" in result.output
