def test_deep_research_pair_merges_on_visible_path() -> None:
    # module 12: followup assistant dropped, events spliced into the parent.
    outline = [
        _ev("thinking", {"call_id": "r1", "call_kind": "agent_loop_round"}, "rephrase", 1),
        _ev("result", {"outline_preview": True}, "outline", 2),
    ]
    followup = [
        _ev("thinking", {"call_id": "r2", "call_kind": "agent_loop_round"}, "search", 3, "researching"),
        _ev("content", {"call_id": "r2"}, "report", 4, "reporting"),
    ]
    messages = [
        _msg(1, "user", None, content="research this"),
        _msg(2, "assistant", 1, events=outline, capability="deep_research"),
        _msg(3, "user", 2, content="ack"),
        _msg(4, "assistant", 3, events=followup, capability="deep_research"),
        _msg(5, "user", 4, content="thanks"),
    ]
    doc = build_session_dsl(messages, stable=True, normalize_ids=True)
    assert [t["kind"] for t in doc["trace"]] == ["user", "assistant", "user", "user"]
    calls = doc["trace"][1]["calls"]
    assert [c["node"] for c in calls] == ["turn:2.1", "turn:2.2"]  # both turns' rounds


def test_deep_research_pair_requires_confirmed_followup() -> None:
    # followup without researching/reporting stage → no merge, two assistants
    messages = [
        _msg(1, "user", None, content="research this"),
        _msg(2, "assistant", 1, events=[_ev("result", {"outline_preview": True}, "o")], capability="deep_research"),
        _msg(3, "user", 2, content="ack"),
        _msg(4, "assistant", 3, events=[_ev("thinking", {"call_id": "x"}, "nope")], capability="deep_research"),
    ]
    doc = build_session_dsl(messages)
    assert len([t for t in doc["trace"] if t["kind"] == "assistant"]) == 2


